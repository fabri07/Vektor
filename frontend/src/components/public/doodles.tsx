/** Renderiza un doodle: trazo blanco, cada path se "dibuja" con delay escalonado. */
function Doodle({ paths, drawDelay = 0 }: { paths: PathList; drawDelay?: number }) {
  return (
    <svg
      viewBox="0 0 240 240"
      fill="none"
      aria-hidden
      focusable={false}
      className="h-auto w-full"
    >
      <g stroke="white" strokeWidth={6} strokeLinecap="round" strokeLinejoin="round">
        {paths.map((d, i) => (
          <path
            key={i}
            d={d}
            pathLength={1}
            className="doodle-path"
            style={{ animationDelay: `${drawDelay + i * 0.08}s` }}
          />
        ))}
      </g>
    </svg>
  );
}

